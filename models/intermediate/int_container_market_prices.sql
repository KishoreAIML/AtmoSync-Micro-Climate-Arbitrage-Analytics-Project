SELECT
    C.EVENT_ID,
    C.CONTAINER_ID,
    C.TIMESTAMP,
    C.CARGO_NAME,
    C.ORIGINAL_VALUE,
    C.LATITUDE,
    C.LONGITUDE,
    C.DEST_LAT,
    C.DEST_LON,
    C.TARGET_TEMP_C,
    C.PULP_TEMP_C,
    C.TEMPERATURE_DRIFT_C,
    C.TEMPERATURE_DRIFT_FLAG,
    C.COMPRESSOR_FAILED,
    C.DOOR_OPEN,
    M.PRICE_ID,
    M.PRICE_TIMESTAMP,
    M.MARKET_ID,
    M.MARKET_NAME,
    M.CITY,
    M.COUNTRY,
    M.PRICE_PER_KG,
    M.CURRENCY,
    M.QUALITY_GRADE,
    M.DEMAND_LEVEL,
    M.SUPPLY_LEVEL,
    M.AVAILABLE_QUANTITY_KG

FROM {{ ref('stg_container_events') }} C

LEFT JOIN {{ ref('stg_market_prices') }} M

    ON C.CARGO_NAME = M.COMMODITY_NAME

    AND ROUND(C.DEST_LAT, 4) = ROUND(M.MARKET_LATITUDE, 4)

    AND ROUND(C.DEST_LON, 4) = ROUND(M.MARKET_LONGITUDE, 4)