CREATE DATABASE CONTAINERS_DATABASE;
USE DATABASE CONTAINERS_DATABASE;
USE SCHEMA PUBLIC;

CREATE TABLE IF NOT EXISTS CONTAINER_EVENTS (
    EVENT_ID VARCHAR(50) PRIMARY KEY,
    SCHEMA_VERSION VARCHAR(20),
    TIMESTAMP TIMESTAMP_NTZ,
    CONTAINER_ID VARCHAR(50),
    CARGO_NAME VARCHAR(100),
    ORIGINAL_VALUE NUMBER(15, 2),
    LATITUDE NUMBER(10, 4),
    LONGITUDE NUMBER(10, 4),
    DEST_LAT NUMBER(10, 6),
    DEST_LON NUMBER(10, 6),
    SPEED_KNOTS NUMBER(10, 2),
    COMPRESSOR_FAILED BOOLEAN,
    HOURS_IN_TRANSIT NUMBER(10, 2),
    TARGET_TEMP_C NUMBER(10, 2),
    AMBIENT_TEMP_C NUMBER(10, 2),
    SUPPLY_TEMP_C NUMBER(10, 2),
    RETURN_TEMP_C NUMBER(10, 2),
    PULP_TEMP_C NUMBER(10, 2),
    TEMPERATURE_DRIFT_C NUMBER(10, 2),
    TEMPERATURE_DRIFT_FLAG BOOLEAN,
    HUMIDITY_PCT NUMBER(10, 2),
    DEW_POINT_C NUMBER(10, 2),
    OXYGEN_PCT NUMBER(10, 2),
    CARBON_DIOXIDE_PCT NUMBER(10, 2),
    ETHYLENE_PPM NUMBER(10, 2),
    SHOCK_X_G NUMBER(10, 2),
    SHOCK_Y_G NUMBER(10, 2),
    SHOCK_Z_G NUMBER(10, 2),
    VIBRATION_HZ NUMBER(10, 2),
    LIGHT_LUX NUMBER(12, 2),
    DOOR_OPEN BOOLEAN,
    PRESSURE_HPA NUMBER(10, 2)
);


USE ROLE ACCOUNTADMIN;
CREATE TABLE IF NOT EXISTS CONTAINERS_DATABASE.PUBLIC.CONTAINER_EVENTS_RAW (
    EVENT_DATA VARIANT,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT USAGE 
